#include <iostream>
#include <windows.h>

int main() {
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);

    int x = 5;
    std::cout << "x=5: 0<x<10 = " << (0 < x < 10) << ", правильно = " << (x > 0 && x < 10) << std::endl;

    x = -5;
    std::cout << "x=-5: 0<x<10 = " << (0 < x < 10) << ", правильно = " << (x > 0 && x < 10) << std::endl;

    /* 
     * Объяснение для x = -5:
     * Запись 0 < x < 10 вычисляется слева направо по частям.
     * Шаг 1: (0 < x) -> (0 < -5). Это ложь (0). 
     * Шаг 2: Полученный 0 сравнивается с 10 -> (0 < 10). Это истина (1).
     * Поэтому результат 1.
     */
    return 0;
}