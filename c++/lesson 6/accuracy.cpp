#include <iostream>
#include <windows.h>

int main() {
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);

    std::cout << "Сумма: " << 0.1 + 0.2 << std::endl;
    /* 
     * Объяснение: На самом деле сумма равна 0.30000000000000004. 
     * Но std::cout по умолчанию выводит только 6 значащих цифр, поэтому хвост скрывается.
     */

    std::cout << "Сумма равна 0.3? " << (0.1 + 0.2 == 0.3) << std::endl;
    /* 
     * Объяснение: Оператор == возвращает 0 (ложь), так как 0.1 и 0.2 нельзя 
     * точно представить в двоичной системе (стандарт IEEE 754). В памяти 
     * числа не равны, поэтому сравнение дает false (0).
     */

    std::cout << "Треть: " << 1.0 / 3.0 << std::endl;
    /* 
     * Объяснение: Результат деления — бесконечная дробь 0.333333333... 
     * std::cout по умолчанию печатает 6 значащих цифр, поэтому хвост не виден.
     */

    return 0;
}